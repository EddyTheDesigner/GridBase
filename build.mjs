import { readFile, writeFile, mkdir } from 'node:fs/promises';
const root = new URL('.', import.meta.url);
const parts = await Promise.all(['native.js','expression.js','core.js','panel.js'].map(f => readFile(new URL('src/'+f,root),'utf8')));
await mkdir(new URL('dist/',root),{recursive:true});
await writeFile(new URL('dist/GridBase.jsx',root),'// GridBase 1.2.0 — EffectCraft dockable ScriptUI panel\n// Generated by build.mjs. Source: src/\n\n'+parts.join('\n\n'));
console.log('Built dist/GridBase.jsx');
