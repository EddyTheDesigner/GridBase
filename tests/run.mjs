import {readFile,writeFile} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
const root=new URL('../',import.meta.url);
const exe=process.env.EFFECTCRAFT_CLI || 'C:/Program Files/EffectCraft/effectcraft-cli.exe';
const src=(await Promise.all(['native.js','expression.js','core.js'].map(f=>readFile(new URL('src/'+f,root),'utf8')))).join('\n');
const saved=fileURLToPath(new URL('tests/verification.ecproj',root));
const file=fileURLToPath(new URL('tests/generated-engine-test.jsx',root));
await writeFile(file,'var TEST_OUTPUT='+JSON.stringify(saved)+';\n'+src+'\n'+await readFile(new URL('tests/engine-tests.js',root),'utf8'));
let report=execFileSync(exe,['script',file,'--empty'],{encoding:'utf8',windowsHide:true,timeout:300000});
const reopen=fileURLToPath(new URL('tests/generated-reopen-test.jsx',root));
await writeFile(reopen,src+`\nvar c=app.project.item(1);c.openInViewer();var gs=GridBase.grids(c);if(gs.length!==1)throw new Error('Reopen grid count');var ls=GridBase.members(gs[0]);if(ls.length!==8)throw new Error('Reopen member count');GridBase.refresh(gs[0]);for(var i=0;i<ls.length;i++){var p=ls[i].transform.position;var v=p.value;if(p.expressionError)throw new Error(p.expressionError);}writeLn('PASS separate-process save/reopen (8 members)');`);
report+=execFileSync(exe,['script',reopen,saved],{encoding:'utf8',windowsHide:true,timeout:300000});
const featureFile=fileURLToPath(new URL('tests/generated-features-v12.jsx',root));
await writeFile(featureFile,src+'\n'+await readFile(new URL('tests/features-v12.js',root),'utf8'));
const features=execFileSync(exe,['script',featureFile,'--empty'],{encoding:'utf8',windowsHide:true,timeout:120000});
report+=features;
await writeFile(new URL('tests/features-v12-results.txt',root),features);
await writeFile(new URL('tests/results.txt',root),report);
console.log(report);
